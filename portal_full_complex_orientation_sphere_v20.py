#!/usr/bin/env python3
"""Sample the full complex three-family portal-orientation sphere for v20.

At fixed portal norm and the previously solved ordered-heavy y_Q, draw a
low-discrepancy sample of complex vectors

    lam_Q_F = kappa * z,  z in C^3, ||z||_2 = 1.

The chosen orientation measure is the rotationally invariant (Haar) measure on
the real five-sphere S^5, generated by normalized complex Gaussian vectors.
Scrambled Sobol replicates make the calculation deterministic and provide a
replicate-spread diagnostic.  This geometric measure is not a UV prior,
posterior, probability of nature, or scan of the remaining portal magnitudes.
"""
from __future__ import annotations

import json
import math
from pathlib import Path
from typing import Any, Iterable

import numpy as np
from scipy.stats import norm, qmc

import channel_fcnc_rates_v20 as rates
import na62_pointwise_limit_v20 as na62
import physical_cf_matching_v20 as physical
