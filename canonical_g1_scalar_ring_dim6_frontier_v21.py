def write_outputs(report: dict[str, Any]) -> None:
    with OUT_JSON.open("w", encoding="utf-8", newline="\n") as handle:
        json.dump(report, handle, indent=2, sort_keys=True)
        handle.write("\n")
    with OUT_MD.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(render_markdown(report))


def load_frozen_report() -> dict[str, Any]:
    report = json.loads(OUT_JSON.read_text(encoding="utf-8"))
    body = dict(report)
    core = body.pop("core_sha256", None)
    if core != _canonical_sha256(body):
        raise ArithmeticError("frozen canonical G1 scalar frontier core drifted")
    if report.get("dependency_pins") != _dependency_rows():
        raise ArithmeticError("frozen canonical G1 scalar frontier dependencies drifted")
    return report


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    if args.write and args.check:
        parser.error("--write and --check are mutually exclusive")
    if args.check:
        report = build_report()
        frozen = load_frozen_report()
        if report != frozen or render_markdown(report) != OUT_MD.read_text(
            encoding="utf-8"
        ):
            raise ArithmeticError("canonical G1 scalar frontier report drifted")
    else:
        report = build_report()
        if args.write:
            write_outputs(report)
    print(
        json.dumps(
            {
                "status": report["status"],
                "overall_state": report["overall_state"],
                "core_sha256": report["core_sha256"],
                "n_failed": report["n_failed"],
                "canonical_G1_closed": report["closure"][
                    "canonical_G1_complete_operator_ring_dim6_closed"
                ],
            },
            sort_keys=True,
        )
    )
    return 0 if report["n_failed"] == 0 else 1


if __name__ == "__main__":
    raise SystemExit(main())
