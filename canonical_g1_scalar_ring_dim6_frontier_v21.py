def _canonical_sha256(value: Any) -> str:
    return hashlib.sha256(
        json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()


def _portable_sha256(path: Path) -> tuple[str, int]:
    payload = path.read_bytes().replace(b"\r\n", b"\n").replace(b"\r", b"\n")
    return hashlib.sha256(payload).hexdigest(), len(payload)


def _dependency_rows() -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for relative in DEPENDENCY_PATHS:
        path = ROOT / relative
        digest, size = _portable_sha256(path)
        rows.append(
            {
                "path": relative,
                "mode": "portable-lf",
                "sha256": digest,
                "normalized_size_bytes": size,
            }
        )
    return rows


def _row(counts: tuple[int, ...]) -> dict[str, Any] | None:
    if not census.neutral(counts, True):
        return None
    multiplicity = census.singlet(census.repchar(counts))
    if not multiplicity:
        return None
    conjugate = census.conj(counts)
    return {
        "count_tuple": list(counts),
        "counts": dict(zip(census.FIELDS, counts, strict=True)),
        "degree": sum(counts),
        "monomial": census.label(counts),
        "charge": census.charge(counts),
        "so10_singlet_multiplicity": multiplicity,
        "conjugate_count_tuple": list(conjugate),
        "conjugate_monomial": census.label(conjugate),
        "self_conjugate": counts == conjugate,
        "conjugacy_orbit_key": list(min(counts, conjugate)),
        "character_dimension": census.character_dimension(census.repchar(counts)),
    }


def enumerate_rows(
    degrees: Iterable[int] = range(1, MAX_DEGREE + 1),
) -> tuple[dict[str, Any], ...]:
    rows: list[dict[str, Any]] = []
    for degree in degrees:
        if type(degree) is not int or not 1 <= degree <= MAX_DEGREE:
            raise ValueError("degrees must be exact integers in [1, 6]")
        for counts in census.comps(degree, len(census.FIELDS)):
            item = _row(counts)
            if item is not None:
                rows.append(item)
    return tuple(sorted(rows, key=lambda item: (item["degree"], item["count_tuple"])))


def _counts(rows: tuple[dict[str, Any], ...]) -> dict[str, Any]:
    orbits = census.orbits(rows)
    complex_by_degree = {
        str(degree): sum(
            row["so10_singlet_multiplicity"]
            for row in rows
            if row["degree"] == degree
        )
        for degree in range(1, MAX_DEGREE + 1)
    }
    orbit_by_degree = {
        str(degree): sum(
            row["so10_singlet_multiplicity"]
            for row in orbits
            if row["degree"] == degree
        )
        for degree in range(1, MAX_DEGREE + 1)
    }
    real_by_degree = {
        str(degree): sum(
            row["real_parameter_count"]
            for row in orbits
            if row["degree"] == degree
        )
        for degree in range(1, MAX_DEGREE + 1)
    }
    sectors_by_degree = {
        str(degree): sum(row["degree"] == degree for row in rows)
        for degree in range(1, MAX_DEGREE + 1)
    }
    return {
        "charge_and_so10_allowed_multidegrees": len(rows),
        "hermitian_conjugacy_orbits": len(orbits),
        "complex_invariant_multiplicity": sum(complex_by_degree.values()),
        "potential_orbit_multiplicity": sum(orbit_by_degree.values()),
        "real_coefficient_count": sum(real_by_degree.values()),
        "multidegrees_by_degree": sectors_by_degree,
        "complex_invariant_multiplicity_by_degree": complex_by_degree,
        "potential_orbit_multiplicity_by_degree": orbit_by_degree,
        "real_coefficient_count_by_degree": real_by_degree,
    }


def _load_renormalizable_component_report() -> dict[str, Any]:
    data = json.loads(RENORMALIZABLE_COMPONENT_REPORT.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise TypeError("renormalizable component report is not an object")
