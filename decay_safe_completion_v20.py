def portal_pair_options(phi_mass_sign: int) -> tuple[tuple[int, int, str], ...]:
    """Finite decay-portal basis using fields already present in the model.

    The returned tuples are ``(X_16, X_16bar, portal)``.  The first two
    options couple the heavy 16 to ``16_F 10_H^(dagger)``; the next two
    couple the heavy 16bar to ``16_F S^(dagger)``; the last uses
    ``16bar 16_F 210_H``.  ``phi_mass_sign`` is +1 for pair charge sum +17
    (a Phi-dagger mass) and -1 for sum -17 (a Phi mass).
    """
    if phi_mass_sign not in (-1, +1):
        raise ValueError("phi_mass_sign must be +1 or -1")
    total = 17 * phi_mass_sign
    return (
        (+1, total - 1, "16 16_F 10_H"),
        (-3, total + 3, "16 16_F 10_H_dagger"),
        (total + 5, -5, "16bar 16_F S"),
        (total - 3, +3, "16bar 16_F S_dagger"),
        (total + 1, -1, "16bar 16_F 210_H"),
    )


def minimality_report() -> dict:
    """Prove the one-pair obstruction and enumerate the three-pair portal basis."""
    # Mixed and gravitational cancellation require n_plus - n_minus = 1.
    # Therefore the number of Phi-massed pairs is odd.  For one pair,
    # x+y=17 and x^3+y^3=1037 imply xy=76 and discriminant -15.
    one_pair_discriminant = 17**2 - 4 * 76
    positive = portal_pair_options(+1)
    negative = portal_pair_options(-1)
    solutions: list[tuple[tuple[int, int], ...]] = []
    for plus_pairs in itertools.combinations_with_replacement(positive, 2):
        for minus_pair in negative:
            fields = plus_pairs + (minus_pair,)
            cubic = sum(x**3 + y**3 for x, y, _portal in fields)
            if cubic == 1037:
                solutions.append(tuple((x, y) for x, y, _portal in fields))
    canonical = ((1, 16), (14, 3), (1, -18))
    return {
        "ansatz": (
            "anomaly sector built only from complete 16+16bar pairs, each "
            "massed renormalizably by one Phi or Phi_dagger (no singlet "
            "anomalons); portal enumeration uses existing 10_H, S, 210_H"
        ),
        "mixed_anomaly_condition": "n_plus - n_minus = 1",
        "pair_number_must_be_odd": True,
        "one_pair_required_product_xy": 76,
        "one_pair_quadratic_discriminant": one_pair_discriminant,
        "one_pair_impossible_even_over_real_charges": one_pair_discriminant < 0,
        "minimum_number_of_pairs": 3,
        "three_pair_portal_basis_solutions": solutions,
        "canonical_solution": canonical,
        "canonical_is_unique_in_portal_basis": solutions == [canonical],
    }


