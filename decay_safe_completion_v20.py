@dataclass(frozen=True)
class Field:
    name: str
    x: int
    pq: int
    centre: int
    spectator_vector: int


# The two added 16_1 fields share the charge state of F and need not be
# duplicated in a necessary-condition charge frontier.  Multiplicity is
# restored in the explicit anomaly and graph audits.
_BASE_FERMIONS: tuple[Field, ...] = (
    Field("F", +1, +1, +1, 0),
    Field("s", +2, +2, +1, +1),
    Field("b", -6, -6, -1, -1),
    Field("Q", +14, -3, +1, 0),
    Field("Bp", +16, -1, -1, 0),
    Field("Bq", +3, +3, -1, 0),
    Field("Bm", -18, -1, -1, 0),
)


def _with_conjugates(fields: Iterable[Field]) -> tuple[Field, ...]:
    answer: list[Field] = []
    for field in fields:
        answer.append(field)
        answer.append(
            Field(
                field.name + "d",
                -field.x,
                -field.pq,
                -field.centre,
                -field.spectator_vector,
            )
        )
    return tuple(answer)


FERMIONS = _with_conjugates(_BASE_FERMIONS)
SCALARS: tuple[Field, ...] = (
    Field("S", +4, +4, 0, 0),
    Field("Sd", -4, -4, 0, 0),
    Field("Hm", -2, -2, +2, 0),
    Field("Hp", +2, +2, +2, 0),
    Field("Phi", +17, 0, 0, 0),
    Field("Phid", -17, 0, 0, 0),
)


@dataclass(frozen=True)
class Operator:
    dimension: int
    x: int
    pq: int
    spectator_vector: int
    n_fermions: int
    labels: tuple[str, ...]

    @property
    def planck_power(self) -> int:
        return self.dimension - 4

    @property
    def label(self) -> str:
        counts = Counter(self.labels)
        return " ".join(
            name if count == 1 else f"{name}^{count}"
            for name, count in sorted(counts.items())
        )

    def as_dict(self) -> dict:
        return {
            "label": self.label,
            "dimension": self.dimension,
            "P": self.planck_power,
            "X": self.x,
            "Q_PQ": self.pq,
            "V_s": self.spectator_vector,
            "n_fermions": self.n_fermions,
        }


@dataclass(frozen=True)
class Closure:
    planck_power: int
    pq: int
    spectator_vector: int
    operators: tuple[Operator, ...]

    def as_dict(self) -> dict:
        counts = Counter(operator.label for operator in self.operators)
        representatives = {operator.label: operator for operator in self.operators}
        return {
            "P": self.planck_power,
            "Q_PQ": self.pq,
            "V_s": self.spectator_vector,
            "operators": [
                {"multiplicity": counts[label], **representatives[label].as_dict()}
                for label in sorted(counts)
            ],
        }


def _layers(fields: Sequence[Field], maximum_number: int) -> tuple[dict, ...]:
    layers: list[dict] = [{(0, 0, 0, 0): ()}]
    for _ in range(maximum_number):
        new: dict[tuple[int, int, int, int], tuple[str, ...]] = {}
        for (x, pq, centre, vector), labels in layers[-1].items():
            for field in fields:
                key = (
                    x + field.x,
                    pq + field.pq,
                    (centre + field.centre) % 4,
                    vector + field.spectator_vector,
                )
                candidate = tuple(sorted(labels + (field.name,)))
                if key not in new or candidate < new[key]:
                    new[key] = candidate
        layers.append(new)
    return tuple(layers)


@lru_cache(maxsize=None)
def operator_frontier(maximum_dimension: int = 16) -> dict[tuple[int, int], Operator]:
    """Necessary-condition frontier tracking the one exact spectator number."""
    fermion_layers = _layers(FERMIONS, 2 * maximum_dimension // 3)
    scalar_layers = _layers(SCALARS, maximum_dimension)
    scalar_index: list[dict[tuple[int, int], list[tuple[int, tuple[str, ...]]]]] = []
    for layer in scalar_layers:
        index: dict[tuple[int, int], list[tuple[int, tuple[str, ...]]]] = defaultdict(list)
        for (x, pq, centre, _vector), labels in layer.items():
            index[(x, centre)].append((pq, labels))
        scalar_index.append(index)

    frontier: dict[tuple[int, int], Operator] = {}
    for n_fermions in range(0, 2 * maximum_dimension // 3 + 1, 2):
        fermion_dimension = 3 * n_fermions // 2
        for n_scalars in range(maximum_dimension - fermion_dimension + 1):
            dimension = fermion_dimension + n_scalars
            if dimension < 5:
                continue
            for (fx, fpq, centre, vector), flabels in fermion_layers[n_fermions].items():
                for spq, slabels in scalar_index[n_scalars].get((-fx, (-centre) % 4), ()):
                    pq = fpq + spq
                    if pq == 0 and vector == 0:
                        continue
                    operator = Operator(
                        dimension,
                        0,
                        pq,
                        vector,
                        n_fermions,
                        flabels + slabels,
                    )
                    key = (pq, vector)
                    old = frontier.get(key)
                    if old is None or (operator.dimension, operator.label) < (
                        old.dimension,
                        old.label,
                    ):
                        frontier[key] = operator
    return frontier


def renormalizable_accidental_audit() -> dict:
    """Conservative superset of all dimension-four-or-lower monomials."""
    fermion_layers = _layers(FERMIONS, 2)
    scalar_layers = _layers(SCALARS, 4)
    dangerous: list[Operator] = []
    for n_fermions in (0, 2):
        fermion_dimension = 3 * n_fermions // 2
        for n_scalars in range(5 - fermion_dimension):
            dimension = fermion_dimension + n_scalars
            if dimension == 0 or dimension > 4:
                continue
            for (fx, fpq, centre, vector), flabels in fermion_layers[n_fermions].items():
                for (sx, spq, scalar_centre, _), slabels in scalar_layers[n_scalars].items():
                    if fx + sx or (centre + scalar_centre) % 4:
                        continue
                    pq = fpq + spq
                    if pq == 0 and vector == 0:
                        continue
                    dangerous.append(
                        Operator(
                            dimension,
                            0,
                            pq,
                            vector,
                            n_fermions,
                            flabels + slabels,
                        )
                    )
    unique = {(operator.dimension, operator.label): operator for operator in dangerous}
    ordered = [unique[key].as_dict() for key in sorted(unique)]
    return {
        "catalogue": "Lorentz parity + Spin(10)-centre necessary-condition superset",
        "pq_or_spectator_vector_breaking_candidates": ordered,
        "accidental_PQ_and_spectator_vector_exact_at_d_le_4": not ordered,
    }


def minimum_vacuum_closure(
    frontier: Mapping[tuple[int, int], Operator],
    maximum_planck_power: int = 16,
) -> Closure | None:
    useful = sorted(
        (operator for operator in frontier.values() if operator.planck_power > 0),
        key=lambda operator: (
            operator.planck_power,
            abs(operator.pq),
            abs(operator.spectator_vector),
            operator.label,
        ),
    )
    start = (0, 0)
    best: dict[tuple[int, int], int] = {start: 0}
    previous: dict[tuple[int, int], tuple[tuple[int, int], Operator]] = {}
    queue: list[tuple[int, int, int]] = [(0, 0, 0)]
    while queue:
        cost, pq, vector = heapq.heappop(queue)
        state = (pq, vector)
        if cost != best.get(state) or cost > maximum_planck_power:
            continue
        if state != start and pq and pq % 4 == 0 and vector == 0:
            path: list[Operator] = []
            while state != start:
                old, operator = previous[state]
                path.append(operator)
                state = old
            path.reverse()
            return Closure(cost, pq, vector, tuple(path))
        for operator in useful:
            new_cost = cost + operator.planck_power
            if new_cost > maximum_planck_power:
                continue
            new_state = (pq + operator.pq, vector + operator.spectator_vector)
            if new_cost < best.get(new_state, math.inf):
                best[new_state] = new_cost
                previous[new_state] = (state, operator)
                heapq.heappush(queue, (new_cost, *new_state))
    return None


def explicit_p8_certificate() -> Closure:
    operators = operator_frontier(16).values()

    def find(dimension: int, required: Counter[str]) -> Operator:
        for operator in operators:
            if operator.dimension == dimension and Counter(operator.labels) == required:
                return operator
        raise RuntimeError(f"explicit operator not found: {required}")

    portal = find(5, Counter({"Q": 1, "b": 1, "Sd": 2}))
    light = find(8, Counter({"s": 4, "Sd": 2}))
    selected = (portal, portal, portal, portal, light)
    return Closure(
        sum(operator.planck_power for operator in selected),
        sum(operator.pq for operator in selected),
        sum(operator.spectator_vector for operator in selected),
        selected,
    )


def p8_one_loop_lorentz_factor() -> int:
    """Explicit two-component contraction for one factorized v20 loop.

    The contraction includes the central ``ss`` bilinear, two ``Qb``
    bilinears, spectator and heavy chirality-flipping propagators, two decay
    vertices, two family kinetic numerators (evaluated in a unit Euclidean
    time-momentum direction), and one conjugate family Yukawa.  Lorentz
    invariance then promotes the unit result to the coefficient of ``p^2``.
    The second factorized loop gives the same factor.
    """
    epsilon_down = ((0, 1), (-1, 0))
    epsilon_up = ((0, -1), (1, 0))
    sigma_time = ((1, 0), (0, 1))
    total = 0
    # s[2], q[2], b[2], qbar[2], f[2], fdot[2]
    for values in itertools.product(range(2), repeat=12):
        s = values[0:2]
        q = values[2:4]
        b = values[4:6]
        qbar = values[6:8]
        family = values[8:10]
        dotted = values[10:12]
        term = epsilon_down[s[0]][s[1]] * epsilon_up[dotted[0]][dotted[1]]
        for index in range(2):
            term *= epsilon_down[q[index]][b[index]]
            term *= epsilon_up[s[index]][b[index]]
            term *= epsilon_up[q[index]][qbar[index]]
            term *= epsilon_down[qbar[index]][family[index]]
            term *= sigma_time[family[index]][dotted[index]]
        total += term
    return total


