def decay_report(
    v_phi: float = 1.0e17,
    heavy_yukawa: float = 1.0,
    example_portal: float = 1.0e-8,
    final_mass: float = 0.0,
) -> dict:
    """One-channel widths with explicit two-body kinematics.

    The massless expression ``|lambda|^2 M/(32 pi)`` is an *upper* benchmark:
    ``Gamma = |lambda|^2 M/(32 pi) * (1 - m_final^2/M^2)^2`` for
    ``m_final < M``.  Lifetime claims that use the massless formula as a
    lower bound on the width are therefore too optimistic.
    """
    mass = heavy_yukawa * v_phi / math.sqrt(2.0)
    massless = example_portal**2 * mass / (32.0 * math.pi)
    if final_mass >= mass:
        kinematic = 0.0
        width = 0.0
    else:
        kinematic = (1.0 - (final_mass / mass) ** 2) ** 2
        width = massless * kinematic
    lifetime = float("inf") if width == 0.0 else HBAR_GEV_S / width
    portal_for_one_second = math.sqrt(32.0 * math.pi * HBAR_GEV_S / mass)
    return {
        "heavy_mass_GeV": mass,
        "width_formula": (
            "Gamma = |lambda|^2 M/(32 pi) * (1-m_final^2/M^2)^2 "
            "<= |lambda|^2 M/(32 pi) for one open normalized channel"
        ),
        "example_portal": example_portal,
        "example_final_mass_GeV": final_mass,
        "example_kinematic_factor": kinematic,
        "example_massless_upper_width_GeV": massless,
        "example_width_GeV": width,
        "example_lifetime_s": lifetime,
        "minimum_normalized_portal_for_lifetime_below_one_second": portal_for_one_second,
        "minimum_portal_scope": (
            "massless upper-width inversion; massive finals require a larger |lambda|"
        ),
        "no_exact_anomalon_number": True,
        "scope": (
            "the Spin(10) tensor audit proves every 16 component has a nonzero "
            "10-channel; a detailed broken-phase Clebsch and flavour fit remains external"
        ),
    }


