#!/usr/bin/env python3
import copy
import unittest
from unittest import mock

import authoritative_full_model_gate_v20 as mod
import g4_sm_closure_binding_v20 as g4_closure


def bind_tool_native_root_evidence(report):
    scaffold = report["executable_scaffold_contract"]
    scaffold.update(
        model_syntax_class="sarah_native",
        tool_native_sarah_syntax=True,
        statically_executable_model_contract=True,
    )
    scaffold["lagrangian"][
        "registered_in_GaugeES_LagrangianInput"
    ] = True
    external = report["external_model_validation"]
    external["schema"] = mod.x_contract_gate.EXTERNAL_VALIDATION_SCHEMA
    external["valid"] = True
    for name in (
        "tool_native_model_format_matches_path",
        "external_process_command_matches_tool",
        "input_manifest_schema_is_supported",
        "input_manifest_sha256_matches_entries",
        "primary_model_is_bound_in_input_manifest",
        "validation_driver_is_bound_to_command",
        "captured_process_log_is_hash_bound",
        "captured_process_log_has_all_required_pass_markers",
    ):
        external["checks"][name] = True


class AuthoritativeFullModelGateTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.report = mod.build_report()

    def test_executes_and_is_blocked(self):
        self.assertEqual(self.report["n_failed"], 0, self.report["failures"])
        self.assertEqual(self.report["overall_state"], "BLOCKED")
        self.assertTrue(self.report["flag"]["authoritative_full_model_gate"])

    def test_legacy_ultimate_is_not_authoritative(self):
        self.assertFalse(
            self.report["legacy_ultimate_gate"]["authoritative_for_full_model"]
        )
        self.assertFalse(self.report["flag"]["legacy_ultimate_gate_authoritative"])
        self.assertTrue(
            self.report["flag"][
                "internal_candidate_approval_is_not_full_model_validation"
            ]
        )
        self.assertEqual(
            self.report["legacy_ultimate_gate"]["reason"],
            "The ultimate gate's tiers are confirmation tiers: its "
            "internal-candidate tier (decisions D3 and D-E) is never "
            "full-model validation, which needs every G1-G8 gate CLOSED "
            "and a unique proton lifetime from the same vacuum.",
        )

    def test_internal_candidate_tier_is_recorded_but_not_promoted(self):
        # G4 CLOSED meets decision D3, but decision D-E holds the internal
        # candidate until G7 is CLOSED, so the committed ultimate gate does
        # not approve it; no approval would ever be full-model validation.
        legacy = self.report["legacy_ultimate_gate"]
        self.assertTrue(legacy["available"])
        self.assertIs(legacy["internal_candidate_approved"], False)
        self.assertIs(legacy["full_phenomenology_approved"], False)
        self.assertIs(
            self.report["checks"]["internal_candidate_not_promoted_to_full_validation"],
            True,
        )
        self.assertFalse(self.report["classification"]["whole_model_validated"])
        self.assertEqual(self.report["overall_state"], "BLOCKED")
        self.assertIn(
            "The internal-candidate tier (decisions D3 and D-E) is not full-model validation.",
            self.report["verdict"],
        )
        # Decision U3 (committed ultimate JSON, regenerated by the chain): the
        # candidate is released, never approved.
        self.assertEqual(legacy["internal_candidate_tier"], "RELEASED_NOT_APPROVED")

    def test_program_verdict_is_recorded_but_never_a_proof_grade_exclusion(self):
        classification = self.report["classification"]
        self.assertEqual(
            classification["program_verdict_code"],
            "NOT_VIABLE_UNDER_DECLARED_STANDARDS__NO_GO_METHOD_LIMITED_AT_G3_X_G8",
        )
        self.assertIs(classification["program_verdict_recorded"], True)
        self.assertIs(classification["whole_model_excluded"], False)
        self.assertIs(self.report["flag"]["whole_model_excluded"], False)
        self.assertIs(
            self.report["checks"]["program_verdict_is_not_a_proof_grade_exclusion"], True
        )
        self.assertEqual(self.report["n_checks"], 11)
        self.assertEqual(self.report["overall_state"], "BLOCKED")
        self.assertIn(
            "The ledger's program verdict (decision U1) is NOT VIABLE as a complete "
            "description of nature under the declared standards (method-limited at G3 x G8); "
            "it is not a proof-grade whole-model exclusion. ",
            self.report["verdict"],
        )

    def test_program_verdict_sentence_and_exclusion_check_fail_closed(self):
        current_ledger = mod.gate_ledger.build_report()
        unrecorded = copy.deepcopy(current_ledger)
        unrecorded["program_verdict"]["recorded"] = False
        unrecorded["program_verdict"]["code"] = mod.gate_ledger.PROGRAM_VERDICT_CODE_UNAVAILABLE
        missing = copy.deepcopy(current_ledger)
        del missing["program_verdict"]
        for label, ledger in (("unrecorded", unrecorded), ("missing", missing)):
            with self.subTest(case=label):
                with mock.patch.object(mod.gate_ledger, "build_report", return_value=ledger):
                    report = mod.build_report()
                self.assertEqual(report["n_failed"], 0, report["failures"])
                self.assertIs(report["classification"]["program_verdict_recorded"], False)
                self.assertNotIn("program verdict (decision U1)", report["verdict"])
                self.assertIs(report["classification"]["whole_model_excluded"], False)
                self.assertEqual(report["overall_state"], "BLOCKED")
        # A forged proof-grade exclusion claim is an integrity failure, never
        # a whole-model exclusion.
        forged = copy.deepcopy(current_ledger)
        forged["program_verdict"]["proof_grade_whole_model_exclusion"] = True
        with mock.patch.object(mod.gate_ledger, "build_report", return_value=forged):
            report = mod.build_report()
        self.assertEqual(report["overall_state"], "EXECUTION_FAIL")
        self.assertIn(
            "gate check: program_verdict_is_not_a_proof_grade_exclusion", report["failures"]
        )
        self.assertIs(report["classification"]["whole_model_excluded"], False)

    def test_no_full_model_claim(self):
        classification = self.report["classification"]
        # The SARAH-attested model contract is consistent; the model is not.
        self.assertTrue(
            classification["authoritative_model_contract_consistent"]
        )
        self.assertTrue(
            classification["tool_native_bound_model_evidence_complete"]
        )
        self.assertFalse(classification["all_g1_g8_closed"])
        self.assertFalse(classification["exact_unique_proton_lifetime"])
        self.assertFalse(classification["proton_decay_observed"])
        self.assertFalse(classification["whole_model_validated"])
        self.assertFalse(classification["whole_model_excluded"])
        self.assertFalse(classification["empirical_discovery"])

    def test_root_resolved_and_downstream_blockers_present(self):
        blockers = set(self.report["blockers"])
        self.assertNotIn(
            mod.x_contract_gate.EXTERNAL_EXECUTION_BLOCKER,
            blockers,
        )
        self.assertNotIn("G1_NOT_CLOSED", blockers)
        self.assertNotIn("G2_NOT_CLOSED", blockers)
        # G3 closes on the SM Pati-Salam track, G4 at its witness benchmark
        # (tree level) and G5 on the same coupling vector.
        self.assertNotIn("G3_NOT_CLOSED", blockers)
        self.assertNotIn("G4_NOT_CLOSED", blockers)
        self.assertNotIn("G5_NOT_CLOSED", blockers)
        for gate in ("G6", "G7", "G8"):
            self.assertIn(f"{gate}_NOT_CLOSED", blockers)
        self.assertTrue(any(item.startswith("PROTON_READINESS_") for item in blockers))

    def test_verdict_scopes_the_g3_and_g4_closures(self):
        verdict = self.report["verdict"]
        self.assertTrue(
            verdict.startswith(
                "The repository remains BLOCKED at full-model scope. On the "
                "attested gauged U(1)_X contract the ledger closes G1, G2, G3, "
                "G4, G5 "
            ),
            verdict,
        )
        self.assertIn(
            " (G3 on the SM Pati-Salam benchmark family only; see "
            "FINAL_G3_ACCEPTANCE_GATE_V20; G4 at the G3 witness benchmark, tree "
            "level; see G4_SM_PATI_SALAM_PHYSICAL_QUOTIENT_V20), but ",
            verdict,
        )
        self.assertIn("G4 at the G3 witness benchmark, tree level", verdict)
        self.assertIn(
            ", but G6, G7, G8 and the unique proton-lifetime derivation "
            "are not closed.",
            verdict,
        )
        self.assertEqual(
            self.report["classification"]["g3_closing_track"], "sm_pati_salam"
        )
        self.assertEqual(
            self.report["classification"]["g4_closure_scope"],
            g4_closure.G4_LEDGER_CLOSED_SCOPE,
        )
        self.assertEqual(self.report["overall_state"], "BLOCKED")

    def test_repaired_contract_promotes_g1_g2_without_full_model_approval(self):
        current_ledger = mod.gate_ledger.build_report()
        inputs = current_ledger["model_contract_reports"]
        repaired_x = copy.deepcopy(inputs["exact_X"])
        repaired_x.update(
            contract_consistent=True,
            blocker=None,
            scientific_blockers=[],
            contract_conflicts=[],
            overall_state="PASS",
        )
        repaired_x["flag"]["contract_consistent"] = True
        repaired_x["flag"]["x_selection_rule_consistently_declared"] = True
        bind_tool_native_root_evidence(repaired_x)
        repaired_ledger = mod.gate_ledger._build_report_from_inputs(
            x_report=repaired_x,
            g1_report=inputs["gauged_G1_character_census"],
            g2_report=inputs["gauged_G2_derivative_audit"],
            filter_report=inputs["gauged_scalar_filter"],
        )

        with mock.patch.object(
            mod.x_contract_gate, "build_report", return_value=repaired_x
        ), mock.patch.object(
            mod.gate_ledger, "build_report", return_value=repaired_ledger
        ):
            report = mod.build_report()

        self.assertEqual(report["n_failed"], 0, report["failures"])
        self.assertEqual(report["overall_state"], "BLOCKED")
        self.assertTrue(
            report["classification"]["authoritative_model_contract_consistent"]
        )
        self.assertNotIn("G1_NOT_CLOSED", report["blockers"])
        self.assertNotIn("G2_NOT_CLOSED", report["blockers"])
        self.assertNotIn("G3_NOT_CLOSED", report["blockers"])
        self.assertNotIn("G4_NOT_CLOSED", report["blockers"])
        self.assertIn("G6_NOT_CLOSED", report["blockers"])
        self.assertIn("G8_NOT_CLOSED", report["blockers"])
        self.assertIn("G3 on the SM Pati-Salam benchmark family only", report["verdict"])
        self.assertIn("G4 at the G3 witness benchmark, tree level", report["verdict"])
        self.assertFalse(report["classification"]["whole_model_validated"])

    def test_unbound_consistency_boolean_is_an_integrity_failure(self):
        # Audit the shipped model without its attestation, then forge the flag.
        contract = copy.deepcopy(
            mod.x_contract_gate.build_report(
                model_text=mod.x_contract_gate.MODEL.read_text(encoding="utf-8")
            )
        )
        contract.update(
            contract_consistent=True,
            blocker=None,
            scientific_blockers=[],
            contract_conflicts=[],
            overall_state="PASS",
        )
        with mock.patch.object(
            mod.x_contract_gate, "build_report", return_value=contract
        ):
            report = mod.build_report()
        self.assertEqual(report["overall_state"], "EXECUTION_FAIL")
        self.assertFalse(
            report["classification"][
                "tool_native_bound_model_evidence_complete"
            ]
        )
        self.assertIn(
            "gate check: consistent_contract_has_tool_native_bound_evidence",
            report["failures"],
        )


if __name__ == "__main__":
    unittest.main()
