"""k4g: Sym^2(210)-valued SO(10)-covariants of the 210 of degree <= 3 and the channel projectors on
Sym^2(210) = 1 + 45 + 54 + 210 + 770 + (1050+1050bar) + 4125 + 5940 + 8910.

A degree-d covariant X(Phi) (symmetric 210x210 matrix) is the Psi-Hessian of a bidegree-(d,2) invariant
F(Phi; Psi, Psi').  By Weyl's first fundamental theorem every O(10)-invariant of 4-forms is a delta-contraction,
i.e. a loopless 4-regular multigraph on the tensor vertices (d copies of Phi, two 'slot' vertices carrying the
basis 4-forms E_I, E_J).  SO(10)-odd (epsilon) covariants are generated by Hodge-dualising one Phi vertex
(a 6-form, degree-6 vertex) and by explicit constructions through M = *(Phi^Phi) and the bilinear B_k.

Channel projectors: polynomials in the so(10) pair operator  C(X) = sum_A T_A X T_A^T  (eigenvalue
24 - C2(kappa)/2) and the gl(10) pair operator  K(X) = sum_ij rho(E_ij) X rho(E_ij)  (eigenvalues 4, -2, -16 on
the GL(10) components S_(2222), S_(221111), Lambda^8), which separates 770 from 1050+1050bar.
All float evaluations at integer points are exact integers as long as every partial sum stays below 2^53
(checked at run time where it matters).
"""
from __future__ import annotations
import itertools
import numpy as np
from scipy import sparse
import k4lib as K

N = 10
DIM = 210
SIX = tuple(itertools.combinations(range(N), 6))
SIX_INDEX = {t: i for i, t in enumerate(SIX)}


# ----------------------------------------------------------------------------- basis tensors and Hodge duals
def _build_E():
    E = np.zeros((DIM, N, N, N, N))
    for I, t in enumerate(K.FOUR):
        for perm in itertools.permutations(range(4)):
            E[(I,) + tuple(t[p] for p in perm)] = K.perm_sign(perm)
    return E


E4 = _build_E()                                   # (210,10,10,10,10)


def dense4(phi):
    return np.einsum("I,Iabcd->abcd", np.asarray(phi, dtype=float), E4)


def hodge_matrix():
    """signed permutation H (210 x 210): (*Phi) as a 6-form vector in the SIX basis = H @ phi."""
    rows, cols, vals = [], [], []
    full = set(range(N))
    for I, t in enumerate(K.FOUR):
        comp = tuple(sorted(full - set(t)))
        rows.append(SIX_INDEX[comp]); cols.append(I); vals.append(K.perm_sign(t + comp))
    return sparse.csr_matrix((vals, (rows, cols)), shape=(DIM, DIM), dtype=np.int64)


HODGE = hodge_matrix()


def dense6(vec6):
    """6-form vector (SIX basis) -> dense antisymmetric 10^6 tensor."""
    T = np.zeros((N,) * 6)
    for I, t in enumerate(SIX):
        v = vec6[I]
        if v == 0:
            continue
        for perm in itertools.permutations(range(6)):
            T[tuple(t[p] for p in perm)] = K.perm_sign(perm) * v
    return T


_PERM6 = None


def dense6_fast(vec6):
    """vectorised version of dense6."""
    global _PERM6
    if _PERM6 is None:
        idx = np.array(SIX)                                   # (210, 6)
        perms = list(itertools.permutations(range(6)))
        sgn = np.array([K.perm_sign(p) for p in perms])
        P = np.array(perms)                                   # (720, 6)
        full = idx[:, P]                                      # (210, 720, 6)
        _PERM6 = (full.reshape(-1, 6), np.repeat(np.arange(DIM), 720), np.tile(sgn, DIM))
    full, which, sgn = _PERM6
    T = np.zeros((N,) * 6)
    T[tuple(full.T)] = sgn * np.asarray(vec6, dtype=float)[which]
    return T


# ----------------------------------------------------------------------------- multigraph enumeration
def regular_multigraphs(degrees):
    """all loopless multigraphs on len(degrees) labelled vertices with the given degree sequence."""
    n = len(degrees)
    pairs = list(itertools.combinations(range(n), 2))
    out = []
    degs = [0] * n

    def rec(idx, m):
        if idx == len(pairs):
            if all(degs[v] == degrees[v] for v in range(n)):
                out.append(tuple(m))
            return
        u, v = pairs[idx]
        maxm = min(degrees[u] - degs[u], degrees[v] - degs[v])
        for k in range(maxm + 1):
            degs[u] += k; degs[v] += k
            rec(idx + 1, m + [k])
            degs[u] -= k; degs[v] -= k

    rec(0, [])
    return pairs, out


def canonical_graphs(degrees, classes):
    """dedupe multigraphs under permutations of vertices inside each class (list of index lists)."""
    pairs, graphs = regular_multigraphs(degrees)
    pidx = {p: i for i, p in enumerate(pairs)}
    perms = []
    for combo in itertools.product(*[itertools.permutations(c) for c in classes]):
        sigma = list(range(len(degrees)))
        for cls, img in zip(classes, combo):
            for a, b in zip(cls, img):
                sigma[a] = b
        perms.append(sigma)
    seen = {}
    for g in graphs:
        key = None
        for sigma in perms:
            m = [0] * len(pairs)
            for (u, v), k in zip(pairs, g):
                a, b = sorted((sigma[u], sigma[v]))
                m[pidx[(a, b)]] = k
            t = tuple(m)
            if key is None or t < key:
                key = t
        seen.setdefault(key, g)
    return pairs, list(seen.values())


LETTERS = "abcdefghijklmnopqrstuvwxyz"


def graph_subscripts(pairs, mult, vtypes):
    """einsum subscripts: vtypes[v] in {'P' (4-form Phi), 'D' (6-form *Phi), 'I', 'J' (slot basis E4)}."""
    slots = {v: [] for v in range(len(vtypes))}
    li = 0
    for (u, v), k in zip(pairs, mult):
        for _ in range(k):
            slots[u].append(LETTERS[li]); slots[v].append(LETTERS[li]); li += 1
    subs = []
    for v, t in enumerate(vtypes):
        s = "".join(slots[v])
        if t in ("I", "J"):
            s = t + s
        subs.append(s)
    return ",".join(subs) + "->IJ"


class GraphCovariant:
    def __init__(self, name, pairs, mult, vtypes, parity):
        self.name = name; self.pairs = pairs; self.mult = mult; self.vtypes = vtypes; self.parity = parity
        self.subs = graph_subscripts(pairs, mult, vtypes)
        self.degree = sum(1 for t in vtypes if t in ("P", "D"))
        self.path = None

    def operands(self, T4, T6):
        ops = []
        for t in self.vtypes:
            if t == "P":
                ops.append(T4)
            elif t == "D":
                ops.append(T6)
            else:
                ops.append(E4)
        return ops

    @staticmethod
    def _flops(info):
        for line in info.splitlines():
            if "Optimized FLOP" in line:
                return float(line.split(":")[1])
        return float("inf")

    def _plan(self, ops):
        """einsum path under a memory limit; if the limited greedy path is hopeless (>2e11 flops) slice over one
        contracted index (10 sub-contractions) and keep the cheapest slicing letter."""
        path, info = np.einsum_path(self.subs, *ops, optimize=("greedy", 3.0e7))
        fl = self._flops(info)
        if fl < 2.0e11:
            self.plan = ("direct", path); return
        best = None
        ins, out = self.subs.split("->")
        terms = ins.split(",")
        for L in sorted(set("".join(terms)) - set("IJ")):
            sub_terms = [t.replace(L, "") for t in terms]
            sub_ops = [np.take(o, 0, axis=t.index(L)) if L in t else o for t, o in zip(terms, ops)]
            sp_, si = np.einsum_path(",".join(sub_terms) + "->" + out, *sub_ops, optimize=("greedy", 3.0e7))
            f2 = self._flops(si) * N
            if best is None or f2 < best[0]:
                best = (f2, L, ",".join(sub_terms) + "->" + out, sp_)
        self.plan = ("sliced",) + best[1:]
        self.sliced_flops = best[0]

    def evaluate(self, T4, T6=None):
        ops = self.operands(T4, T6)
        if self.path is None:
            self._plan(ops); self.path = self.plan
        if self.plan[0] == "direct":
            return np.einsum(self.subs, *ops, optimize=self.plan[1])
        _, L, subs2, path2 = self.plan
        terms = self.subs.split("->")[0].split(",")
        X = None
        for v in range(N):
            sub_ops = [np.take(o, v, axis=t.index(L)) if L in t else o for t, o in zip(terms, ops)]
            Y = np.einsum(subs2, *sub_ops, optimize=path2)
            X = Y if X is None else X + Y
        return X


def all_graph_covariants(max_degree=3, include_odd=True):
    covs = []
    for d in range(0, max_degree + 1):
        vtypes = ["P"] * d + ["I", "J"]
        degrees = [4] * (d + 2)
        classes = [list(range(d)), [d, d + 1]]
        pairs, graphs = canonical_graphs(degrees, classes)
        for gi, g in enumerate(graphs):
            covs.append(GraphCovariant(f"e{d}_{gi}", pairs, g, vtypes, +1))
        if include_odd and d >= 1:
            vtypes = ["D"] + ["P"] * (d - 1) + ["I", "J"]
            degrees = [6] + [4] * (d - 1) + [4, 4]
            classes = [[0], list(range(1, d)), [d, d + 1]]
            pairs, graphs = canonical_graphs(degrees, classes)
            for gi, g in enumerate(graphs):
                covs.append(GraphCovariant(f"o{d}_{gi}", pairs, g, vtypes, -1))
    return covs


# ----------------------------------------------------------------------------- pair operators on 210x210 matrices
GENS = [g.astype(float).tocsr() for g in K.generators()]
GENS_T = [g.T.tocsr() for g in GENS]


def _rho(i, j):
    """gl(10) generator e_i ^ i_j on 4-forms (sparse int)."""
    rows, cols, vals = [], [], []
    for col, t in enumerate(K.FOUR):
        if j not in t:
            continue
        pos = t.index(j)
        red = t[:pos] + t[pos + 1:]
        sg = (-1) ** pos
        st, s2 = K.sorted_with_sign((i,) + red)
        if st is None:
            continue
        rows.append(K.FOUR_INDEX[st]); cols.append(col); vals.append(sg * s2)
    return sparse.csr_matrix((vals, (rows, cols)), shape=(DIM, DIM), dtype=np.int64)


RHO = [[_rho(i, j) for j in range(N)] for i in range(N)]
RHO_F = [[m.astype(float).tocsr() for m in row] for row in RHO]


def C_so(X):
    out = np.zeros_like(X)
    for g, gt in zip(GENS, GENS_T):
        out += g @ (X @ gt)
    return out


def K_gl(X):
    out = np.zeros_like(X)
    for i in range(N):
        for j in range(N):
            r = RHO_F[i][j]
            out += r @ (X @ r)
    return out


# exact (object) versions via index arrays
def _perm_data(m):
    coo = m.tocoo()
    return coo.row, coo.col, coo.data.astype(np.int64)


GEN_IDX = [_perm_data(g) for g in K.generators()]
RHO_IDX = [[_perm_data(RHO[i][j]) for j in range(N)] for i in range(N)]


def _left(idx, X):
    r, c, s = idx
    out = np.zeros_like(X); out[:] = 0
    out[r, :] = s[:, None] * X[c, :]
    return out


def _right_T(idx, X):
    """X @ g^T where g has data (r,c,s): (X g^T)[:, r] = s * X[:, c]."""
    r, c, s = idx
    out = np.zeros_like(X); out[:] = 0
    out[:, r] = s[None, :] * X[:, c]
    return out


def _right(idx, X):
    """X @ g: (X g)[:, c] = s * X[:, r]."""
    r, c, s = idx
    out = np.zeros_like(X); out[:] = 0
    out[:, c] = s[None, :] * X[:, r]
    return out


def C_so_exact(X):
    out = np.zeros_like(X); out[:] = 0
    for idx in GEN_IDX:
        out = out + _left(idx, _right_T(idx, X))
    return out


def K_gl_exact(X):
    out = np.zeros_like(X); out[:] = 0
    for i in range(N):
        for j in range(N):
            idx = RHO_IDX[i][j]
            out = out + _left(idx, _right(idx, X))
    return out


# channel data: (so eigenvalue, gl eigenvalue)
C2 = {"1": 0, "45": 16, "54": 20, "210": 24, "770": 36, "1050": 36, "4125": 48, "5940": 44, "8910": 56}
SO_EIG = {k: 24 - v // 2 for k, v in C2.items()}
GL_EIG = {"1": 4, "54": 4, "770": 4, "4125": 4, "8910": 4, "210": -2, "1050": -2, "5940": -2, "45": -16}
CHANNELS = ("1", "45", "54", "210", "770", "1050", "4125", "5940", "8910")
CHANNEL_DIM = {"1": 1, "45": 45, "54": 54, "210": 210, "770": 770, "1050": 2100, "4125": 4125, "5940": 5940, "8910": 8910}
SO_VALUES = sorted(set(SO_EIG.values()))          # 8 distinct
GL_VALUES = (4, -2, -16)


def projector_coefficients(channel):
    """returns (so_poly, gl_poly) as lists of Fractions: P = so_poly(C) * gl_poly(K)  (gl_poly = [1] if not needed)."""
    from fractions import Fraction
    import sympy as sp
    x = sp.symbols("x")
    c = SO_EIG[channel]
    so = sp.Integer(1)
    for c2 in SO_VALUES:
        if c2 != c:
            so *= (x - c2) / sp.Integer(c - c2)
    so_poly = [Fraction(int(sp.fraction(co)[0]), int(sp.fraction(co)[1])) for co in reversed(sp.Poly(sp.expand(so), x).all_coeffs())]
    shared = [k for k in CHANNELS if SO_EIG[k] == c]
    if len(shared) == 1:
        return so_poly, [Fraction(1)]
    k0 = GL_EIG[channel]
    gl = sp.Integer(1)
    for k2 in GL_VALUES:
        if k2 != k0:
            gl *= (x - k2) / sp.Integer(k0 - k2)
    gl_poly = [Fraction(int(sp.fraction(co)[0]), int(sp.fraction(co)[1])) for co in reversed(sp.Poly(sp.expand(gl), x).all_coeffs())]
    return so_poly, gl_poly


PROJ = {ch: projector_coefficients(ch) for ch in CHANNELS}


# ---- antisymmetric carrier Lambda^2(210) = 45 + 210 + 945 + 945 + 5940 + 6930 + 6930bar
# so pair-operator eigenvalues 16, 12, 8, 2, -2 (verified numerically: Krylov roots exact to 1e-13);
# gl pair operator K has eigenvalues 2 and -8 on Lambda^2(210) and splits the two 945 copies (both present).
ANTI_SO_EIG = {"45a": 16, "210a": 12, "945A": 8, "945B": 8, "5940a": 2, "6930": -2}
ANTI_GL_EIG = {"945A": 2, "945B": -8}
ANTI_SO_VALUES = (16, 12, 8, 2, -2)
ANTI_GL_VALUES = (2, -8)
ANTI_CHANNELS = ("945A", "945B", "6930")          # the channels not available in Sym^2(210)
ANTI_M_EXPECTED = {"945A": 4, "945B": 4, "6930": 4}   # degree-<=3 multiplicities per carrier copy (6930+bar real: 2x2)


def _lagrange_poly(target, values):
    from fractions import Fraction
    import sympy as sp
    x = sp.symbols("x")
    pol = sp.Integer(1)
    for v in values:
        if v != target:
            pol *= (x - v) / sp.Integer(target - v)
    return [Fraction(int(sp.fraction(co)[0]), int(sp.fraction(co)[1])) for co in reversed(sp.Poly(sp.expand(pol), x).all_coeffs())]


def anti_projector_coefficients(channel):
    from fractions import Fraction
    so_poly = _lagrange_poly(ANTI_SO_EIG[channel], ANTI_SO_VALUES)
    if channel in ANTI_GL_EIG:
        gl_poly = _lagrange_poly(ANTI_GL_EIG[channel], ANTI_GL_VALUES) + [Fraction(0)]   # padded to quadratic form
    else:
        gl_poly = [Fraction(1)]
    return so_poly, gl_poly


PROJ_ANTI = {ch: anti_projector_coefficients(ch) for ch in ANTI_CHANNELS}


def so_powers(X, nmax=7, exact=False):
    pows = [X]
    for _ in range(nmax):
        pows.append(C_so_exact(pows[-1]) if exact else C_so(pows[-1]))
    return pows


def project_all(X, exact=False):
    """dict channel -> P_channel X (float, or object/Fraction if exact)."""
    from fractions import Fraction
    pows = so_powers(X, 7, exact)
    if exact:
        Kx = K_gl_exact(X); Kxx = K_gl_exact(Kx)
    else:
        Kx = K_gl(X); Kxx = K_gl(Kx)
    out = {}
    for ch in CHANNELS:
        so_poly, gl_poly = PROJ[ch]
        if len(gl_poly) == 1:
            acc = None
            for n, co in enumerate(so_poly):
                term = (co if exact else float(co)) * pows[n]
                acc = term if acc is None else acc + term
            out[ch] = acc
        else:
            # gl_poly(K) X = g0 X + g1 K X + g2 K^2 X, then apply so_poly(C)
            Y = (gl_poly[0] if exact else float(gl_poly[0])) * X + (gl_poly[1] if exact else float(gl_poly[1])) * Kx \
                + (gl_poly[2] if exact else float(gl_poly[2])) * Kxx
            pw = so_powers(Y, 7, exact)
            acc = None
            for n, co in enumerate(so_poly):
                term = (co if exact else float(co)) * pw[n]
                acc = term if acc is None else acc + term
            out[ch] = acc
    return out


def to_object(X):
    """float64 matrix of exact integers -> object array of Python ints."""
    assert np.all(np.abs(X) < 2.0 ** 52), "float64 exactness bound violated"
    Xi = np.rint(X)
    assert np.array_equal(Xi, X)
    out = np.empty(X.shape, dtype=object)
    for idx in np.ndindex(X.shape):
        out[idx] = int(Xi[idx])
    return out


def frob(X, Y):
    return float(np.sum(X * Y))
