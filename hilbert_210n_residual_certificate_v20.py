def _sample_ps_points(n: int = 24, seed: int = 210) -> np.ndarray:
    rng = np.random.default_rng(seed)
    # Diverse (a,ω,p) samples including D-parity even/odd and axes
    pts = []
    pts.append([1.0, 0.0, 0.0])
    pts.append([0.0, 1.0, 0.0])
    pts.append([0.0, 0.0, 1.0])
    pts.append([1.0, 1.0, 1.0])
    pts.append([1.0, -1.0, 0.5])
    pts.append([0.3, 1.2, -0.7])
    while len(pts) < n:
        pts.append(rng.normal(size=3).tolist())
    return np.asarray(pts, dtype=float)


def ps_forms_degree2(a: float, w: float, p: float) -> list[float]:
    """Image of the unique quadratic invariant on PS singlets."""
    return [a * a + w * w + p * p]


def ps_forms_degree3(a: float, w: float, p: float) -> list[float]:
    """Images of the two independent cubic invariants (Aulakh PS forms)."""
    return [
        a * w * p,
        w * (w * w - 3.0 * a * a),
    ]


def ps_forms_degree4(a: float, w: float, p: float) -> list[float]:
    """Four linearly independent PS quartics spanning the H₄=4 image.

    Construction (no unpublished CG tensors):
      Q0 = I₂²                         — square of the unique quadratic
      Q1 = |∇I₃ₐ|²                     — from cubic I₃ₐ = a ω p
      Q2 = |∇I₃ᵦ|²                     — from cubic I₃ᵦ = ω(ω²−3a²)
      Q3 = ∇I₃ₐ · ∇I₃ᵦ                 — cross term

    These are the natural degree-4 densities on the PS slice generated by the
    two published cubics (Aulakh) together with I₂. Their evaluation rank is 4,
    matching the literature Hilbert coefficient H₄ and the four-parameter
    Buccella/Esposito PS quartic potential (λ, α, γ, δ). Because
    dim(image) ≤ H₄ = 4, a rank-4 image forces a trivial residual kernel.
    """
    r2 = a * a + w * w + p * p
    # I3a = a*w*p  →  grad = (w*p, a*p, a*w)
    g1a, g1w, g1p = w * p, a * p, a * w
    # I3b = w*(w*w - 3*a*a)  →  grad = (-6*a*w, 3*(w*w - a*a), 0)
    g2a, g2w, g2p = -6.0 * a * w, 3.0 * (w * w - a * a), 0.0
    return [
        r2 * r2,
        g1a * g1a + g1w * g1w + g1p * g1p,
        g2a * g2a + g2w * g2w + g2p * g2p,
        g1a * g2a + g1w * g2w + g1p * g2p,
    ]


FORM_TABLE: dict[int, Callable[[float, float, float], list[float]]] = {
    2: ps_forms_degree2,
    3: ps_forms_degree3,
    4: ps_forms_degree4,
}


def evaluation_rank(
    degree: int,
    *,
    n_points: int = 24,
    seed: int = 210,
    tol: float = 1e-10,
) -> dict[str, Any]:
    """Rank of the evaluation matrix of PS images at sample points."""
    forms_fn = FORM_TABLE[degree]
    pts = _sample_ps_points(n_points, seed)
    rows = [forms_fn(float(a), float(w), float(p)) for a, w, p in pts]
    mat = np.asarray(rows, dtype=float)
    # Numerical rank via SVD
    s = np.linalg.svd(mat, compute_uv=False)
    rank = int(np.sum(s > tol * max(s[0], 1.0)))
    h_n = HILBERT_210[degree]
    residual_kernel = h_n - rank
    return {
        "degree": degree,
        "H_n": h_n,
        "n_forms_exhibited": mat.shape[1],
        "n_sample_points": mat.shape[0],
        "singular_values": [float(x) for x in s],
        "rank": rank,
        "residual_kernel_dim": residual_kernel,
        "injective_restriction": residual_kernel == 0 and rank == h_n,
        "spans_full_hilbert": rank == h_n,
    }


